#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Plot fc threshold-calibration data collected by collect_fc_data.py.

The script is intentionally offline: it only reads the CSV generated by the
shape sweep and writes PNG figures. This keeps plotting reproducible from an
archived experiment directory without requiring ROS, Gazebo, or rosbag replay.
"""

import argparse
import csv
import math
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter


def setup_paper_style():
    matplotlib.rcParams.update({
        "font.family": "Times New Roman",
        "font.size": 24,
        "axes.titlesize": 28,
        "axes.labelsize": 28,
        "xtick.labelsize": 24,
        "ytick.labelsize": 24,
        "legend.fontsize": 21,
        "mathtext.fontset": "cm",
        "svg.fonttype": "none",
    })


def _as_float(value):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if math.isnan(v) or math.isinf(v):
        return None
    return v


def load_rows(path):
    with open(path) as fp:
        return list(csv.DictReader(fp))


def values(rows, key):
    return [v for v in (_as_float(row.get(key)) for row in rows) if v is not None]


def paired_values(rows, x_key, y_key):
    pairs = []
    for row in rows:
        x = _as_float(row.get(x_key))
        y = _as_float(row.get(y_key))
        if x is not None and y is not None:
            pairs.append((x, y))
    return pairs


def mean(xs):
    return sum(xs) / float(len(xs)) if xs else None


def pearson_r(pairs):
    if len(pairs) < 2:
        return None
    xs = [x for x, _y in pairs]
    ys = [y for _x, y in pairs]
    x_bar = mean(xs)
    y_bar = mean(ys)
    cov = sum((x - x_bar) * (y - y_bar) for x, y in pairs)
    x_var = sum((x - x_bar) ** 2 for x in xs)
    y_var = sum((y - y_bar) ** 2 for y in ys)
    denom = math.sqrt(x_var * y_var)
    return cov / denom if denom > 0.0 else None


def linear_fit(pairs):
    if len(pairs) < 2:
        return None
    xs = [x for x, _y in pairs]
    ys = [y for _x, y in pairs]
    x_bar = mean(xs)
    y_bar = mean(ys)
    denom = sum((x - x_bar) ** 2 for x in xs)
    if denom <= 0.0:
        return None
    slope = sum((x - x_bar) * (y - y_bar) for x, y in pairs) / denom
    return slope, y_bar - slope * x_bar


def percentile(xs, p):
    xs = sorted(xs)
    if not xs:
        return None
    k = (len(xs) - 1) * p / 100.0
    lo = int(k)
    hi = min(lo + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (k - lo)


def median(xs):
    return percentile(xs, 50.0)


def propose_thresholds(xs, hard_pct, min_frac, safety):
    if not xs:
        return None, None
    hard_min = max(0.0, percentile(xs, hard_pct) * safety)
    soft_min = median(xs) * min_frac
    return hard_min, max(hard_min, soft_min)


def ensure_dir(path):
    if not os.path.isdir(path):
        os.makedirs(path)


def save(fig, out_dir, base_name, formats, tight=True):
    paths = []
    if tight:
        fig.tight_layout()
    for fmt in formats:
        path = os.path.join(out_dir, "%s.%s" % (base_name, fmt))
        fig.savefig(path, dpi=180, bbox_inches="tight", pad_inches=0.08)
        paths.append(path)
    plt.close(fig)
    return paths


def threshold_label(symbol, suffix, value, label_values=False):
    suffix_space = r"\;" if suffix == "min" else ""
    if label_values:
        return r"$r_%s^{\mathrm{%s}}%s = %.3f$" % (symbol, suffix, suffix_space, value)
    return r"$r_%s^{\mathrm{%s}}$" % (symbol, suffix)


def add_threshold_lines(ax, hard_min, soft_min, symbol, label_values=False):
    if hard_min is not None:
        label = threshold_label(symbol, "hard", hard_min, label_values)
        ax.axvline(hard_min, color="tab:red", linestyle="-", linewidth=3.0,
                   label=label)
    if soft_min is not None:
        label = threshold_label(symbol, "min", soft_min, label_values)
        ax.axvline(soft_min, color="tab:green", linestyle="-", linewidth=3.0,
                   label=label)


def hide_zero_tick(value, pos):
    return "" if abs(value) < 1e-12 else "%g" % value


def plot_histograms(rows, out_dir, thresholds, bins, formats, name_prefix, paper_style=False):
    f = values(rows, "fc_f_min_mean")
    t = values(rows, "fc_t_min_mean")
    fig, axes = plt.subplots(1, 2, figsize=(12, 5.0))
    for ax, xs, title, xlabel, th, xlim, symbol in (
        (axes[0], f, "Force Volume", r"$r_f$ [N]", thresholds["force"], (0.0, 2.5), "f"),
        (axes[1], t, "Torque Volume", r"$r_\tau$ [N m]", thresholds["torque"], (0.0, 2.5), r"\tau"),
    ):
        hist_kwargs = {"range": xlim} if paper_style else {}
        ax.hist(xs, bins=bins, color="0.35", edgecolor="white", **hist_kwargs)
        add_threshold_lines(ax, th[0], th[1], symbol, label_values=paper_style)
        if not paper_style:
            ax.set_title(title)
        ax.set_xlabel(xlabel)
        if ax is axes[0]:
            ax.set_ylabel("Samples")
        if paper_style:
            ax.set_xlim(xlim)
            ax.set_ylim(bottom=0.0)
            ax.set_xticks([0.5 * k for k in range(int(xlim[1] / 0.5) + 1)])
            ax.yaxis.set_major_formatter(FuncFormatter(hide_zero_tick))
            ax.tick_params(axis="both", which="both", length=0, top=False, right=False)
        ax.grid(True, alpha=0.25)
        ax.legend(loc="upper right", frameon=True)
    fig.subplots_adjust(wspace=0.22)
    return save(fig, out_dir, name_prefix + "_distribution", formats, tight=False)


def plot_scatter(rows, out_dir, thresholds, formats, name_prefix):
    f = values(rows, "fc_f_min_mean")
    t = values(rows, "fc_t_min_mean")
    n = min(len(f), len(t))
    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    ax.scatter(f[:n], t[:n], s=28, alpha=0.75, color="tab:blue")
    fh, fm = thresholds["force"]
    th, tm = thresholds["torque"]
    if fh is not None:
        ax.axvline(fh, color="tab:red", linestyle="--", linewidth=1.3,
                   label="force hard_min")
    if fm is not None:
        ax.axvline(fm, color="tab:green", linestyle="--", linewidth=1.3,
                   label="force min")
    if th is not None:
        ax.axhline(th, color="tab:red", linestyle=":", linewidth=1.3,
                   label="torque hard_min")
    if tm is not None:
        ax.axhline(tm, color="tab:green", linestyle=":", linewidth=1.3,
                   label="torque min")
    ax.set_title("Force vs torque volume radius")
    ax.set_xlabel("fc_f_min")
    ax.set_ylabel("fc_t_min")
    ax.grid(True, alpha=0.25)
    ax.legend(loc="best")
    return save(fig, out_dir, name_prefix + "_force_vs_torque", formats)


def plot_sequence(rows, out_dir, thresholds, formats, name_prefix):
    f = values(rows, "fc_f_min_mean")
    t = values(rows, "fc_t_min_mean")
    idx = list(range(max(len(f), len(t))))
    fig, axes = plt.subplots(2, 1, figsize=(11, 6), sharex=True)
    for ax, xs, title, ylabel, th in (
        (axes[0], f, "Force volume radius by sample", "fc_f_min", thresholds["force"]),
        (axes[1], t, "Torque volume radius by sample", "fc_t_min", thresholds["torque"]),
    ):
        ax.plot(idx[:len(xs)], xs, marker="o", markersize=3, linewidth=1.0)
        hard_min, soft_min = th
        if hard_min is not None:
            ax.axhline(hard_min, color="tab:red", linestyle="--", linewidth=1.2)
        if soft_min is not None:
            ax.axhline(soft_min, color="tab:green", linestyle="--", linewidth=1.2)
        ax.set_title(title)
        ax.set_ylabel(ylabel)
        ax.grid(True, alpha=0.25)
    axes[1].set_xlabel("sample index")
    return save(fig, out_dir, name_prefix + "_by_sample", formats)


def command_joint_keys(rows):
    if not rows:
        return []
    return [key for key in rows[0].keys() if key.startswith("cmd_")]


def plot_joint_relations(rows, out_dir, formats, name_prefix):
    keys = command_joint_keys(rows)
    if not keys:
        return None
    ncols = 3
    nrows = int(math.ceil(len(keys) / float(ncols)))
    fig, axes = plt.subplots(nrows, ncols, figsize=(12, 3.3 * nrows), squeeze=False)
    force = values(rows, "fc_f_min_mean")
    torque = values(rows, "fc_t_min_mean")
    for i, key in enumerate(keys):
        ax = axes[i // ncols][i % ncols]
        xs = values(rows, key)
        n = min(len(xs), len(force), len(torque))
        ax.scatter(xs[:n], force[:n], s=18, alpha=0.65, label="fc_f_min")
        ax.scatter(xs[:n], torque[:n], s=18, alpha=0.65, label="fc_t_min")
        ax.set_title(key.replace("cmd_", ""))
        ax.set_xlabel("commanded joint angle [rad]")
        ax.set_ylabel("inradius")
        ax.grid(True, alpha=0.25)
    for j in range(len(keys), nrows * ncols):
        axes[j // ncols][j % ncols].axis("off")
    axes[0][0].legend(loc="best")
    return save(fig, out_dir, name_prefix + "_by_joint", formats)


def plot_altitude_correlation(rows, out_dir, formats, name_prefix, paper_style=False):
    specs = [
        ("fc_f_min_mean", r"$r_f$", "tab:orange"),
        ("fc_t_min_mean", r"$r_\tau$", "tab:blue"),
    ]
    fig, axes = plt.subplots(1, 2, figsize=(12, 5.0), sharex=True)
    for ax, (fc_key, ylabel, color) in zip(axes, specs):
        pairs = paired_values(rows, "altitude_mean", fc_key)
        if pairs:
            xs = [x for x, _y in pairs]
            ys = [y for _x, y in pairs]
            ax.scatter(xs, ys, s=22 if paper_style else 18,
                       alpha=0.65, color=color, edgecolors="none")
            fit = linear_fit(pairs)
            if fit is not None:
                slope, intercept = fit
                x_min = min(xs)
                x_max = max(xs)
                ax.plot([x_min, x_max],
                        [slope * x_min + intercept, slope * x_max + intercept],
                        color="black", linewidth=1.8, linestyle="--")
            r = pearson_r(pairs)
            if r is not None:
                ax.text(
                    0.04, 0.94, r"$r = %.3f$" % r,
                    transform=ax.transAxes, ha="left", va="top")
        ax.set_xlabel("altitude_mean [m]")
        ax.set_ylabel(ylabel)
        ax.grid(True, alpha=0.25)
        if not paper_style:
            ax.set_title("%s vs altitude_mean" % fc_key)
    fig.subplots_adjust(wspace=0.28)
    return save(fig, out_dir, name_prefix + "_altitude_correlation", formats,
                tight=False)


def write_summary(rows, out_dir, thresholds, name_prefix):
    f = values(rows, "fc_f_min_mean")
    t = values(rows, "fc_t_min_mean")
    path = os.path.join(out_dir, name_prefix + "_plot_summary.txt")
    with open(path, "w") as fp:
        fp.write("samples: %d\n" % len(rows))
        for name, xs in (("fc_f_min", f), ("fc_t_min", t)):
            if not xs:
                fp.write("%s: no data\n" % name)
                continue
            fp.write(
                "%s: min=%.6f p5=%.6f p25=%.6f median=%.6f p75=%.6f max=%.6f\n"
                % (name, min(xs), percentile(xs, 5), percentile(xs, 25),
                   median(xs), percentile(xs, 75), max(xs)))
        fp.write("force_thresholds hard_min=%.6f min=%.6f\n" % thresholds["force"])
        fp.write("torque_thresholds hard_min=%.6f min=%.6f\n" % thresholds["torque"])
        for key in ("fc_f_min_mean", "fc_t_min_mean"):
            pairs = paired_values(rows, "altitude_mean", key)
            r = pearson_r(pairs)
            if r is not None:
                fp.write(
                    "pearson_altitude_mean_vs_%s: r=%.6f samples=%d\n"
                    % (key, r, len(pairs)))
    return path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", help="fc_sweep.csv generated by collect_fc_data.py")
    parser.add_argument("--out-dir", default=None,
                        help="directory for figure outputs (default: <csv dir>/figures)")
    parser.add_argument("--hard-pct", type=float, default=5.0)
    parser.add_argument("--min-frac", type=float, default=0.8)
    parser.add_argument("--safety", type=float, default=1.0)
    parser.add_argument("--bins", type=int, default=20)
    parser.add_argument("--formats", nargs="+", default=["png"],
                        choices=["png", "svg", "pdf"],
                        help="figure formats to write")
    parser.add_argument("--name-prefix", default="fc",
                        help="prefix for output figure and summary file names")
    parser.add_argument("--paper-style", action="store_true",
                        help="use publication-oriented labels, fonts, ticks, and axes")
    parser.add_argument("--plots", nargs="+", default=["all"],
                        choices=["all", "distribution", "scatter", "sequence",
                                 "joint", "altitude"],
                        help="which plots to write")
    args = parser.parse_args()
    if args.paper_style:
        setup_paper_style()

    rows = load_rows(args.csv)
    out_dir = args.out_dir or os.path.join(os.path.dirname(os.path.abspath(args.csv)), "figures")
    ensure_dir(out_dir)

    thresholds = {
        "force": propose_thresholds(values(rows, "fc_f_min_mean"),
                                    args.hard_pct, args.min_frac, args.safety),
        "torque": propose_thresholds(values(rows, "fc_t_min_mean"),
                                     args.hard_pct, args.min_frac, args.safety),
    }

    plots = set(args.plots)
    write_all = "all" in plots
    outputs = []
    if write_all or "distribution" in plots:
        outputs.append(plot_histograms(
            rows, out_dir, thresholds, args.bins, args.formats, args.name_prefix,
            paper_style=args.paper_style))
    if write_all or "scatter" in plots:
        outputs.append(plot_scatter(rows, out_dir, thresholds, args.formats, args.name_prefix))
    if write_all or "sequence" in plots:
        outputs.append(plot_sequence(rows, out_dir, thresholds, args.formats, args.name_prefix))
    if write_all or "joint" in plots:
        joint_plot = plot_joint_relations(rows, out_dir, args.formats, args.name_prefix)
        if joint_plot:
            outputs.append(joint_plot)
    if write_all or "altitude" in plots:
        outputs.append(plot_altitude_correlation(
            rows, out_dir, args.formats, args.name_prefix,
            paper_style=args.paper_style))
    outputs.append(write_summary(rows, out_dir, thresholds, args.name_prefix))

    for output in outputs:
        if isinstance(output, list):
            for path in output:
                print(path)
        else:
            print(output)


if __name__ == "__main__":
    main()
